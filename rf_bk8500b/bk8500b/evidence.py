"""RFDS-008 evidence and diagnostics engine for :mod:`bk8500b` / ``rf_bk8500b``.

Every public keyword call in ``BK8500BLibrary`` is recorded as a *run* under
``results/session/rf_bk8500b/<timestamp>_<run_id>/`` (override with the
``RFDS_EVIDENCE_ROOT`` environment variable): one JSON Lines entry per
event/operation/error, redacted arguments, the underlying protocol exchange
(SCPI text or legacy binary frames, hex-encoded), a device-identity snapshot,
and — once ``Disconnect Electronic Load``/``Disconnect All Electronic
Loads``/``Disconnect`` runs — a ``run_summary.json`` + ``evidence_manifest.json``
pair with a SHA-256 hash per artifact. ``Export Diagnostic Bundle`` zips the
whole thing up for troubleshooting.

This module is deliberately complementary to, not a replacement for, this
driver's existing structured-diagnostics infrastructure:

- :mod:`bk8500b.diagnostics` already defines ``AuditSink``/``MetricsSink``
  protocols and an ``AuditEvent`` dataclass that :class:`bk8500b.execution.
  CommandExecutor` calls on every write/query (operation name, risk class,
  outcome, timing). :class:`EvidenceAuditSink`/:class:`EvidenceMetricsSink`
  below *implement* those protocols and forward into this engine, so
  connecting evidence recording is one constructor argument, not a parallel
  system fighting the existing one for the same seam.
- ``BK8500BLibrary._translate`` already centralizes error translation for
  (most) keyword bodies; this module does not touch it. Operation-level
  recording is applied uniformly via a decorator on every ``@keyword`` method
  instead (see ``rf_bk8500b`` integration in ``BK8500BLibrary/library.py`),
  which does not depend on every keyword happening to route through
  ``_translate`` and so cannot silently miss one.
- The pre-existing ``evidence/hardware_conformance/<version>_<port>_<date>/``
  directories elsewhere in this repository (see e.g. rf_bk8500_load) are
  point-in-time archives generated by post-processing a completed Robot
  ``output.xml``. This engine is different: a live, always-on, per-session
  system that also works outside a formal Robot suite run.

Implements the subset of RFDS-008 that makes a concrete troubleshooting
difference for this driver (structured, correlated, redacted, integrity-hashed
evidence). Deliberately out of scope, consistent with the rf_phidget_relay
reference implementation this was adapted from: a shared cross-driver
package (none exists in this repository yet), log rotation/backpressure
policy, cryptographic signing, and literal RFDS-007 error codes (RFDS-007
was not available while writing this; ``category`` below is a pragmatic
mapping of this driver's own exception hierarchy).
"""

