class EvidenceAuditSink:
    """Implements :class:`bk8500b.diagnostics.AuditSink`.

    Forwards every :class:`AuditEvent` the executor already produces (one per
    write/query transaction: operation name, risk class, outcome, detail,
    context) into the evidence run as a structured event.
    """

    def __init__(self, run: EvidenceRun | NullEvidenceRun, *, session_alias: str | None = None) -> None:
        self._run = run
        self._session_alias = session_alias

    def record(self, event: AuditEvent) -> None:
        level = "ERROR" if event.outcome in (
            CommandOutcome.FAILED_NOT_SENT,
            CommandOutcome.OUTCOME_INDETERMINATE,
        ) else "INFO"
        self._run.emit_event(
            f"AUDIT_{event.operation.upper()}",
            f"{event.operation}: {event.detail}",
            level=level,
            data={
                "audit_event_id": event.event_id,
                "risk": event.risk.value,
                "outcome": event.outcome.value,
                "context": dict(event.context),
            },
            session_alias=self._session_alias,
        )


class EvidenceMetricsSink:
    """Implements :class:`bk8500b.diagnostics.MetricsSink`; forwards counters as DEBUG events."""

    def __init__(self, run: EvidenceRun | NullEvidenceRun, *, session_alias: str | None = None) -> None:
        self._run = run
        self._session_alias = session_alias

    def increment(self, name: str, value: int = 1, **labels: str) -> None:
        self._run.emit_event(
            "METRIC_INCREMENT", f"{name} +{value}", level="TRACE",
            data={"name": name, "value": value, **labels}, session_alias=self._session_alias,
        )

    def observe(self, name: str, value: float, **labels: str) -> None:
        self._run.emit_event(
            "METRIC_OBSERVE", f"{name}={value}", level="TRACE",
            data={"name": name, "value": value, **labels}, session_alias=self._session_alias,
        )


class TracingTransport:
    """Wraps a real :class:`Transport` to log raw bytes at the wire boundary.

    ``AuditEvent`` above carries the *outcome* of a transaction (operation
    name, risk, timing) but not the literal bytes sent/received — this class
    is the true RFDS-019 protocol-boundary observation point: every
    ``write``/``read``/``read_until`` call is traced as a hex-encoded payload
    (safe for both SCPI ASCII and the 26-byte legacy binary frame codec)
    before being forwarded unchanged to the wrapped transport.
    """

    def __init__(self, inner: Transport, run: EvidenceRun | NullEvidenceRun, *, session_alias: str | None = None) -> None:
        self._inner = inner
        self._run = run
        self._session_alias = session_alias

    @property
    def is_open(self) -> bool:
        return self._inner.is_open

    def open(self) -> None:
        self._inner.open()

    def close(self) -> None:
        self._inner.close()

    def write(self, data: bytes, *, timeout_s: float | None = None) -> int:
        self._run.log_protocol(
            "outbound", "serial",
            f"write {len(data)}B: {data.hex()} (ascii={data!r})",
            session_alias=self._session_alias,
        )
        return self._inner.write(data, timeout_s=timeout_s)

    def read(self, size: int, *, timeout_s: float | None = None) -> bytes:
        result = self._inner.read(size, timeout_s=timeout_s)
        self._run.log_protocol(
            "inbound", "serial",
            f"read {len(result)}B: {result.hex()} (ascii={result!r})",
            session_alias=self._session_alias,
        )
        return result

    def read_until(self, terminator: bytes, *, maximum_bytes: int, timeout_s: float | None = None) -> bytes:
        result = self._inner.read_until(terminator, maximum_bytes=maximum_bytes, timeout_s=timeout_s)
        self._run.log_protocol(
            "inbound", "serial",
            f"read_until {terminator!r} -> {len(result)}B: {result.hex()} (ascii={result!r})",
            session_alias=self._session_alias,
        )
        return result

    def reset_input_buffer(self) -> None:
        self._inner.reset_input_buffer()

    def reset_output_buffer(self) -> None:
        self._inner.reset_output_buffer()


class EvidenceListener:
    """Register with ``--listener bk8500b.evidence.EvidenceListener`` to correlate
    events with the active Robot suite/test/keyword. Entirely optional."""

    ROBOT_LISTENER_API_VERSION = 3

    def start_suite(self, data: Any, result: Any) -> None:
        _current_suite_id.set(getattr(data, "longname", str(data)))

    def end_suite(self, data: Any, result: Any) -> None:
        _current_suite_id.set(None)

    def start_test(self, data: Any, result: Any) -> None:
        _current_test_id.set(getattr(data, "longname", str(data)))

    def end_test(self, data: Any, result: Any) -> None:
        _current_test_id.set(None)

    def start_keyword(self, data: Any, result: Any) -> None:
        _current_keyword.set(getattr(data, "name", str(data)))

    def end_keyword(self, data: Any, result: Any) -> None:
        _current_keyword.set(None)


