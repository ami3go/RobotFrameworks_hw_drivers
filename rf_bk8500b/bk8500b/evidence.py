# ---------------------------------------------------------------------------
# Time, identifiers, JSON safety, redaction
# ---------------------------------------------------------------------------

def _utc_now_iso() -> str:
    now = datetime.now(timezone.utc)
    return now.strftime("%Y-%m-%dT%H:%M:%S.") + f"{now.microsecond // 1000:03d}Z"


def _new_run_id() -> str:
    now = datetime.now(timezone.utc)
    return f"run-{now.strftime('%Y%m%dT%H%M%S')}.{now.microsecond // 1000:03d}Z-{uuid.uuid4().hex[:8]}"


def _json_default(obj: Any) -> Any:
    if isinstance(obj, Path):
        return str(obj)
    if isinstance(obj, (bytes, bytearray)):
        return obj.hex()
    return repr(obj)


def _looks_sensitive(key: str) -> bool:
    lowered = key.lower()
    return any(marker in lowered for marker in _SENSITIVE_KEY_MARKERS)


def _json_safe(value: Any) -> Any:
    if value is None or isinstance(value, (str, int, float, bool)):
        return value
    if isinstance(value, (bytes, bytearray)):
        return value.hex()
    if isinstance(value, Mapping):
        return redact_mapping(value)
    if isinstance(value, (list, tuple, set)):
        return [_json_safe(item) for item in value]
    return repr(value)


def redact_mapping(data: Mapping[str, Any]) -> dict[str, Any]:
    """Redact keys that look sensitive; recurse into nested mappings (RFDS-008 §29.3)."""
    result: dict[str, Any] = {}
    for key, value in data.items():
        if _looks_sensitive(str(key)):
            result[key] = {"value": "<REDACTED>", "redacted": True, "reason": "credential"}
        else:
            result[key] = _json_safe(value)
    return result


def _classify_exception(exc: BaseException) -> str:
    """Approximate error category from this driver's own exception hierarchy.

    RFDS-008 §17 calls for "RFDS error category and code defined by RFDS-007";
    RFDS-007 itself was not available while writing this, so this maps
    ``bk8500b.exceptions`` names to a small stable category set instead.
    """
    name = type(exc).__name__
    if "Configuration" in name or "UnsupportedModel" in name or "UnsupportedFeature" in name:
        return "VALIDATION"
    if "InvalidStateTransition" in name:
        return "STATE"
    if "Protection" in name or "Unsafe" in name:
        return "SAFETY"
    if "Transport" in name or "Timeout" in name or "Indeterminate" in name or "Malformed" in name:
        return "HARDWARE"
    if "Range" in name:
        return "VALIDATION"
    return "UNKNOWN"


def _safe_distribution_version(dist_name: str) -> str | None:
    try:
        import importlib.metadata as importlib_metadata

        return importlib_metadata.version(dist_name)
    except Exception:
        return None


def _safe_module_version(module_name: str) -> str | None:
    try:
        module = __import__(module_name)
        return getattr(module, "__version__", None)
    except Exception:
        return None


def _sanitized_hostname() -> str:
    try:
        return hashlib.sha256(socket.gethostname().encode("utf-8")).hexdigest()[:12]
    except Exception:
        return "UNKNOWN"


